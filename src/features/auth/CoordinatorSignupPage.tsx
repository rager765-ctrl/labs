import React, { useState } from 'react';
import { Link, useNavigate, useSearchParams } from 'react-router-dom';
import {
  AlertCircle,
  Lock,
  Mail,
  User,
  ShieldAlert,
  ShieldCheck,
  IdCard,
  Building2,
  Award,
  Sparkles,
  MapPin,
  ArrowLeft,
} from 'lucide-react';
import { useApp } from '../../context/AppContext';
import {
  AuthField,
  AuthSelect,
  AuthLayout,
  PasswordStrength,
  friendlyAuthError,
  passwordChecks,
} from './AuthComponents';

const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

export const DEPARTMENTS = [
  { value: 'School of Computing & Data Science', label: 'School of Computing & Data Science' },
  { value: 'Department of Computer Science', label: 'Department of Computer Science' },
  { value: 'Department of Information Technology', label: 'Department of Information Technology' },
  { value: 'Department of Electrical & Electronic Engineering', label: 'Department of Electrical & Electronic Engineering' },
  { value: 'Department of Mathematical Sciences', label: 'Department of Mathematical Sciences' },
  { value: 'Faculty of Engineering & Technology', label: 'Faculty of Engineering & Technology' },
];

export const DESIGNATIONS = [
  { value: 'Senior Lab Coordinator', label: 'Senior Lab Coordinator' },
  { value: 'Lead Innovations Lab Coordinator', label: 'Lead Innovations Lab Coordinator' },
  { value: 'Laboratory Instructor / TA', label: 'Laboratory Instructor / TA' },
  { value: 'Lecturer / Assistant Professor', label: 'Lecturer / Assistant Professor' },
  { value: 'Head of Laboratory Operations', label: 'Head of Laboratory Operations' },
];

export const CoordinatorSignupPage: React.FC = () => {
  const [searchParams] = useSearchParams();
  const inviteToken = searchParams.get('invite') || '';
  const navigate = useNavigate();
  const { registerCoordinator } = useApp();

  const [name, setName] = useState('');
  const [email, setEmail] = useState('');
  const [staffId, setStaffId] = useState('');
  const [department, setDepartment] = useState(DEPARTMENTS[0].value);
  const [designation, setDesignation] = useState(DESIGNATIONS[0].value);
  const [labRoom, setLabRoom] = useState('');
  const [password, setPassword] = useState('');
  const [confirmPassword, setConfirmPassword] = useState('');
  const [agree, setAgree] = useState(false);
  const [errors, setErrors] = useState<Record<string, string>>({});
  const [formError, setFormError] = useState('');
  const [submitting, setSubmitting] = useState(false);

  // If coordinator link is not opened with an invitation token, display secure access restriction
  if (!inviteToken) {
    return (
      <AuthLayout
        title="Coordinator Access Restricted"
        subtitle="Coordinator registration is invite-only and requires an active department link."
      >
        <div style={{ textAlign: 'center', padding: '24px 8px' }}>
          <div
            style={{
              width: '64px',
              height: '64px',
              borderRadius: '50%',
              backgroundColor: 'rgba(239, 68, 68, 0.12)',
              color: 'var(--color-danger-700)',
              display: 'grid',
              placeItems: 'center',
              margin: '0 auto 16px auto',
              border: '1px solid rgba(239, 68, 68, 0.25)',
            }}
          >
            <ShieldAlert size={32} />
          </div>

          <h2 style={{ fontSize: '18px', fontWeight: 700, color: 'var(--color-ink-900)', margin: '0 0 8px 0' }}>
            Department Invitation Required
          </h2>

          <p style={{ fontSize: '13px', color: 'var(--color-ink-500)', lineHeight: '20px', margin: '0 0 24px 0' }}>
            Faculty coordinator registration is restricted and cannot be created through public sign-up. Please open the unique onboarding invitation link generated by your department head or lead coordinator.
          </p>

          <Link
            to="/login"
            className="btn-primary"
            style={{
              display: 'inline-flex',
              alignItems: 'center',
              justifyContent: 'center',
              gap: '8px',
              height: '42px',
              padding: '0 24px',
              textDecoration: 'none',
              width: '100%',
              fontSize: '13px',
              fontWeight: 600,
            }}
          >
            <ArrowLeft size={16} />
            <span>Return to Sign In</span>
          </Link>
        </div>
      </AuthLayout>
    );
  }

  const validate = (): boolean => {
    const nextErrors: Record<string, string> = {};
    if (name.trim().length < 2) nextErrors.name = 'Enter your full name and title.';
    if (!EMAIL_RE.test(email.trim())) nextErrors.email = 'Enter a valid work email.';
    if (!/^[A-Za-z0-9-]{3,}$/.test(staffId.trim())) nextErrors.staffId = 'Enter your staff/faculty ID (e.g. FAC-8042).';
    if (!department) nextErrors.department = 'Select your team or department.';
    if (!designation) nextErrors.designation = 'Select your faculty title.';

    const checks = passwordChecks(password);
    if (!checks.length || !checks.upper || !checks.number) {
      nextErrors.password = 'Use at least 8 characters, including an uppercase letter and a number.';
    }
    if (password !== confirmPassword) {
      nextErrors.confirm = "Passwords don't match.";
    }
    if (!agree) {
      nextErrors.agree = 'You must confirm laboratory oversight agreement.';
    }

    setErrors(nextErrors);
    return Object.keys(nextErrors).length === 0;
  };

  const handleSubmit = async (event: React.FormEvent) => {
    event.preventDefault();
    setFormError('');
    if (!validate()) return;

    setSubmitting(true);
    try {
      await registerCoordinator(
        email.trim(),
        password,
        name.trim(),
        staffId.trim().toUpperCase(),
        department,
        designation,
        labRoom.trim(),
        inviteToken.trim() || undefined
      );
      navigate('/coordinator', { replace: true });
    } catch (error: any) {
      setFormError(error?.message || friendlyAuthError(error?.code));
    } finally {
      setSubmitting(false);
    }
  };

  return (
    <AuthLayout
      title="Coordinator Account Setup"
      subtitle="Complete your profile to manage Innovations Lab meeting sessions, track arrivals and departures, and review attendance."
      wide
    >
      <form className="auth-form" onSubmit={handleSubmit} noValidate>
        {/* Verification Status Chip */}
        <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', marginBottom: '8px' }}>
          <div className="auth-badge auth-badge--coordinator">
            <ShieldCheck size={13} />
            <span>Innovations Lab Coordinator</span>
          </div>
          <div className="auth-badge auth-badge--verified" title="Department invitation token attached">
            <Sparkles size={12} />
            <span>Invitation Verified</span>
          </div>
        </div>

        {formError && (
          <div className="auth-alert auth-alert--error" role="alert">
            <AlertCircle size={16} />
            <span>{formError}</span>
          </div>
        )}

        <AuthField
          id="coordinator-name"
          label="Full Name & Title"
          autoComplete="name"
          placeholder="e.g. Dr. Elena Vance"
          icon={<User size={18} />}
          value={name}
          onChange={e => { setName(e.target.value); if (errors.name) setErrors(prev => ({ ...prev, name: '' })); }}
          error={errors.name}
          required
        />

        <div className="auth-row auth-row--2">
          <AuthField
            id="coordinator-email"
            label="Work Email"
            type="email"
            autoComplete="email"
            inputMode="email"
            placeholder="e.vance@university.edu"
            icon={<Mail size={18} />}
            value={email}
            onChange={e => { setEmail(e.target.value); if (errors.email) setErrors(prev => ({ ...prev, email: '' })); }}
            error={errors.email}
            required
          />

          <AuthField
            id="coordinator-staff-id"
            label="Staff ID"
            placeholder="FAC-8042"
            autoComplete="off"
            icon={<IdCard size={18} />}
            value={staffId}
            onChange={e => { setStaffId(e.target.value.toUpperCase()); if (errors.staffId) setErrors(prev => ({ ...prev, staffId: '' })); }}
            error={errors.staffId}
            required
          />
        </div>

        <div className="auth-row auth-row--2">
          <AuthSelect
            id="coordinator-department"
            label="Team / Department"
            icon={<Building2 size={18} />}
            placeholder="Select team or department"
            options={DEPARTMENTS}
            value={department}
            onChange={e => { setDepartment(e.target.value); if (errors.department) setErrors(prev => ({ ...prev, department: '' })); }}
            error={errors.department}
            required
          />

          <AuthSelect
            id="coordinator-designation"
            label="Coordinator Role"
            icon={<Award size={18} />}
            placeholder="Select title"
            options={DESIGNATIONS}
            value={designation}
            onChange={e => { setDesignation(e.target.value); if (errors.designation) setErrors(prev => ({ ...prev, designation: '' })); }}
            error={errors.designation}
            required
          />
        </div>

        <AuthField
          id="coordinator-lab-room"
          label="Innovations Lab / Office Location"
          placeholder="e.g. Main Lab, Room 304B"
          icon={<MapPin size={18} />}
          value={labRoom}
          onChange={e => setLabRoom(e.target.value)}
        />

        <p className="auth-section-label">Account Security</p>

        <AuthField
          id="coordinator-password"
          label="Password"
          type="password"
          autoComplete="new-password"
          placeholder="Create a strong password"
          icon={<Lock size={18} />}
          value={password}
          onChange={e => { setPassword(e.target.value); if (errors.password) setErrors(prev => ({ ...prev, password: '' })); }}
          error={errors.password}
          required
        />
        <PasswordStrength password={password} />

        <AuthField
          id="coordinator-confirm-password"
          label="Confirm Password"
          type="password"
          autoComplete="new-password"
          placeholder="Repeat your password"
          icon={<Lock size={18} />}
          value={confirmPassword}
          onChange={e => { setConfirmPassword(e.target.value); if (errors.confirm) setErrors(prev => ({ ...prev, confirm: '' })); }}
          error={errors.confirm}
          required
        />

        <div>
          <label className="auth-checkbox" htmlFor="coordinator-agree">
            <input
              id="coordinator-agree"
              type="checkbox"
              checked={agree}
              onChange={e => { setAgree(e.target.checked); if (errors.agree) setErrors(prev => ({ ...prev, agree: '' })); }}
              aria-invalid={!!errors.agree}
            />
            <span>
              I confirm that I am an authorized Innovations Lab coordinator and agree to manage attendee records and meeting sessions responsibly.
            </span>
          </label>
          {errors.agree && (
            <span className="auth-field__error" role="alert" style={{ marginTop: 6 }}>
              <AlertCircle size={12} /> {errors.agree}
            </span>
          )}
        </div>

        <button
          type="submit"
          className="btn-primary auth-submit"
          disabled={submitting}
          id="coordinator-submit"
          style={{ height: '46px', fontSize: '14px', fontWeight: 600 }}
        >
          {submitting ? (
            <>
              <span className="auth-spinner" aria-hidden="true" /> Setting up coordinator account…
            </>
          ) : (
            'Complete Coordinator Registration'
          )}
        </button>

        <div className="auth-role-note">
          <span className="auth-role-note__icon">
            <ShieldCheck size={16} />
          </span>
          <span>
            Signing up with this invitation establishes your verified <strong>Coordinator status</strong>, granting access to create sessions, display QR check-in codes, and manage attendance records.
          </span>
        </div>
      </form>

      <div className="auth-footer">
        Already have an account? <Link to="/login" className="auth-link" id="coordinator-to-login">Sign in here</Link>
      </div>
    </AuthLayout>
  );
};
